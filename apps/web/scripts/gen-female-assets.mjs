/**
 * Generates `src/data/femaleAssets.ts` (web + mobile, byte-identical — see
 * scripts/check-parity.mjs) by scanning `cdn/public/female/`.
 *
 * The female image set is deliberately partial and grows over time (see cdn/README.md
 * and docs/IMAGES.md for the base library this mirrors) — a category or exercise with
 * no female photo yet should fall back to the male one, not 404. Rather than have every
 * call site guess at what exists, this bakes the actual answer into a committed file:
 * whatever is really sitting in `cdn/public/female/` when this last ran, nothing more.
 *
 * Run:  node scripts/gen-female-assets.mjs   (after adding/removing a file under
 * cdn/public/female/) — the same "regenerate by hand and commit" pattern gen-body-muscles.mjs
 * and gen-catalog-json.mts use, not a build step.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const WEB_ROOT = resolve(HERE, '..')
const NATIVE_ROOT = resolve(WEB_ROOT, '..', 'mobile')
const FEMALE_DIR = resolve(WEB_ROOT, '..', '..', 'cdn', 'public', 'female')

function pngsIn(dir) {
  try {
    return readdirSync(dir).filter((f) => f.endsWith('.png')).sort()
  } catch {
    return []
  }
}

const heroDir = join(FEMALE_DIR, 'hero')
const imagesDir = join(FEMALE_DIR, 'images')

const heroCategories = pngsIn(heroDir).map((f) => f.replace(/\.png$/, ''))

const exerciseImages = []
let categoryDirs = []
try {
  categoryDirs = readdirSync(imagesDir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()
} catch {
  /* no images/ yet */
}
for (const cat of categoryDirs) {
  for (const file of pngsIn(join(imagesDir, cat))) {
    exerciseImages.push(`${cat}/${file}`)
  }
}

const lit = (arr) => arr.map((s) => `  '${s}',`).join('\n')

const ts = `// AUTO-GENERATED by scripts/gen-female-assets.mjs from cdn/public/female/ — DO NOT EDIT BY HAND.
// Regenerate after adding or removing a file under that directory, then commit the result.
// See that script's header comment for why this is a committed manifest rather than a
// runtime directory listing (the CDN is a static-assets Worker with no listing API).

/** Category keys with a female hero image, e.g. 'chest' -> cdn/public/female/hero/chest.png */
export const FEMALE_HERO: ReadonlySet<string> = new Set([
${lit(heroCategories)}
])

/** '<category>/<file>.png' pairs that exist under cdn/public/female/images/. */
export const FEMALE_EXERCISE_IMAGES: ReadonlySet<string> = new Set([
${lit(exerciseImages)}
])
`

for (const root of [WEB_ROOT, NATIVE_ROOT]) {
  const out = join(root, 'src', 'data', 'femaleAssets.ts')
  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, ts)
  console.log('wrote', out)
}

console.log(`hero: ${heroCategories.length} categories`)
console.log(`exercise images: ${exerciseImages.length}`)
