/**
 * Generates `src/data/bodyMuscles.ts` (for BOTH the web app and grindz-native)
 * from `traced-muscles.json`.
 *
 * `traced-muscles.json` is produced by `scripts/trace/` — a vectorisation of the
 * reference artwork `muscles-worked-close-neutral-grip-lat-pulldown.png`. That PNG is
 * a flat vector render, so its dark separator ink is a closed network and the muscles
 * are simply the enclosed regions: connected-component labelling recovers the
 * segmentation the illustrator drew, and potrace turns each region into béziers.
 * See scripts/trace/README.md for the pipeline and how labels were assigned.
 *
 * This generator's job is the app-facing part:
 *   1. validate the traced geometry (unique ids, valid categories, 2dp coords,
 *      no styling baked into path data);
 *   2. emit the `BodyMuscle` contract, the `intensityOf` resolver and the two arrays;
 *   3. write byte-identical output to both projects.
 *
 * Geometry only — no fill/stroke/style is ever emitted. The renderer applies theme colour.
 *
 * Run:  node scripts/gen-body-muscles.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const WEB_ROOT = resolve(HERE, '..')
const NATIVE_ROOT = resolve(WEB_ROOT, '..', 'grindz-native')
const SRC_JSON = join(HERE, 'traced-muscles.json')

/** The only valid category values. `cardio` has no muscle of its own and stays unused. */
const VALID = new Set(['chest', 'back', 'shoulders', 'biceps', 'triceps', 'legs', 'abs', 'cardio'])

const src = JSON.parse(readFileSync(SRC_JSON, 'utf8'))
const VIEWBOX = src.viewBox

// ---------------------------------------------------------------------------
// validate
// ---------------------------------------------------------------------------
const problems = []
for (const view of ['front', 'back']) {
  const ids = new Set()
  let bodies = 0
  for (const m of src[view]) {
    if (ids.has(m.id)) problems.push(`${view}: duplicate id ${m.id}`)
    ids.add(m.id)
    if (m.category !== null && !VALID.has(m.category)) problems.push(`${view}:${m.id} invalid category ${m.category}`)
    if (m.kind === 'silhouette' && m.category !== null) problems.push(`${view}:${m.id} silhouette must not have a category`)
    if (m.kind === 'muscle' && m.category === undefined) problems.push(`${view}:${m.id} missing category`)
    if (!['left', 'right', 'center'].includes(m.side)) problems.push(`${view}:${m.id} bad side ${m.side}`)
    if (/fill|stroke|style|="/.test(m.path)) problems.push(`${view}:${m.id} path carries styling`)
    if (!/^M/.test(m.path)) problems.push(`${view}:${m.id} path does not start with M`)
    const over = m.path.match(/\.\d{3,}/g)
    if (over) problems.push(`${view}:${m.id} coords beyond 2dp: ${over.slice(0, 3)}`)
    if (m.id === 'body') bodies++
  }
  if (bodies !== 1) problems.push(`${view}: expected exactly one 'body' silhouette, found ${bodies}`)
  // every left has a right and vice versa
  const bySide = {}
  for (const m of src[view]) if (m.side !== 'center') (bySide[m.group] ??= []).push(m.side)
  for (const [g, sides] of Object.entries(bySide))
    if (!(sides.includes('left') && sides.includes('right'))) problems.push(`${view}: group ${g} has ${sides} — not a L/R pair`)
}
if (problems.length) {
  console.error('traced geometry failed validation:')
  for (const p of problems) console.error('  -', p)
  process.exit(1)
}

// ---------------------------------------------------------------------------
// emit
// ---------------------------------------------------------------------------
const lit = (v) => (v === null ? 'null' : `'${v}'`)
const rows = (arr) =>
  arr
    .map(
      (m) =>
        `  { id: '${m.id}', name: '${m.name.replace(/'/g, "\\'")}', category: ${lit(m.category)}, group: '${m.group}', side: '${m.side}', kind: '${m.kind}', path: '${m.path}' },`
    )
    .join('\n')

const ts = `// AUTO-GENERATED by scripts/gen-body-muscles.mjs from scripts/traced-muscles.json — DO NOT EDIT BY HAND.
// The artwork is a trace of ${src.source}; see scripts/trace/README.md.
// Geometry only: no fill, stroke or style is baked in, so the renderer is free to
// apply theme colour.
export const BODY_VIEWBOX = '${VIEWBOX}'

/** How strongly a muscle is worked. The map can render two intensities. */
export type MuscleIntensity = 'primary' | 'secondary'

/** Anatomical side — the subject's own left/right, not the viewer's. */
export type MuscleSide = 'left' | 'right' | 'center'

/**
 * 'muscle'     — a muscle island; takes the muscle fill, and the highlight when worked.
 * 'silhouette' — the body itself plus the head, hands and feet. Drawn first, in the
 *                outline colour; it is what shows through the gaps between muscles.
 *                Never highlights.
 */
export type MuscleKind = 'muscle' | 'silhouette'

export interface BodyMuscle {
  /** stable, unique within its view (e.g. 'latissimus_dorsi_left') */
  id: string
  /** human label, e.g. 'Latissimus Dorsi (L)' */
  name: string
  /** app category key this muscle belongs to, or null for untrainable regions
   *  (the body silhouette, head, neck, hands, feet) — those render but never highlight. */
  category: string | null
  /** the muscle this shape belongs to, ignoring side. Left and right entries of
   *  the same muscle share a group, so both halves can be addressed at once. */
  group: string
  side: MuscleSide
  kind: MuscleKind
  /** SVG path 'd' data only */
  path: string
}

/**
 * What the caller passes as "trained". A plain Set of category keys lights every
 * matching muscle at full strength; a Map lets a caller distinguish primary movers
 * from secondary ones, keyed by category key, muscle group, or muscle id.
 */
export type TrainedInput = Set<string> | Map<string, MuscleIntensity>

/**
 * Resolve how a muscle should render. Most specific key wins: muscle id, then
 * group, then category. Returns null when the muscle is not worked at all.
 */
export function intensityOf(m: BodyMuscle, trained: TrainedInput): MuscleIntensity | null {
  if (m.kind === 'silhouette') return null
  if (trained instanceof Set) {
    if (trained.has(m.id) || trained.has(m.group)) return 'primary'
    return m.category && trained.has(m.category) ? 'primary' : null
  }
  return trained.get(m.id) ?? trained.get(m.group) ?? (m.category ? trained.get(m.category) ?? null : null)
}

export const FRONT_MUSCLES: BodyMuscle[] = [
${rows(src.front)}
]

export const BACK_MUSCLES: BodyMuscle[] = [
${rows(src.back)}
]
`

for (const root of [WEB_ROOT, NATIVE_ROOT]) {
  const out = join(root, 'src', 'data', 'bodyMuscles.ts')
  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, ts)
  console.log('wrote', out)
}

const count = (v, k) => src[v].filter((m) => m.kind === k).length
console.log(`viewBox ${VIEWBOX}`)
console.log(`front: ${src.front.length} shapes (${count('front', 'muscle')} muscles, ${count('front', 'silhouette')} silhouette)`)
console.log(`back:  ${src.back.length} shapes (${count('back', 'muscle')} muscles, ${count('back', 'silhouette')} silhouette)`)
